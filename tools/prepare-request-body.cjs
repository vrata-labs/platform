const fs = require('node:fs');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const ts = require('typescript');
const hash = s => crypto.createHash('sha1').update('blob '+Buffer.byteLength(s)+'\0').update(s).digest('hex');
const sourcePath='apps/api/src/index.ts';
const before=fs.readFileSync(sourcePath,'utf8');
const moduleText=fs.readFileSync('apps/api/src/request-body.ts','utf8');
const testText=fs.readFileSync('apps/api/src/request-body.test.ts','utf8');
assert.equal(hash(before),'15eeecbed189c159b2cc0c27f99bcf78d0c8ac94');
assert.equal(hash(moduleText),'4cfad0633eb1e21e7a0507b795a7637dda161e52');
assert.equal(hash(testText),'a4d4365b0e7d32d26063a126117fdffcc72c56b6');
const start=before.indexOf('function parseBody<T>');
const end=before.indexOf('function sanitizeSceneBundleId',start);
assert.ok(start>0 && end>start);
const block=before.slice(start,end);
const anchor='import { parseMultipartBoundary, parseMultipartFormData, textPart, filePart } from "./multipart-form-data.js";\n';
assert.equal(before.split(anchor).length,2);
const addedImport='\nimport { parseBody, readRequestBuffer } from "./request-body.js";\n';
const after=(before.slice(0,start)+before.slice(end)).replace(anchor,anchor+addedImport);
assert.equal(hash(after),'2d15c45f0a40ad6bc6844a6c28d1c174854fd6b8');
assert.equal(after.replace(addedImport,'').replace('function sanitizeSceneBundleId',block+'function sanitizeSceneBundleId'),before);
const parse=s=>ts.createSourceFile('index.ts',s,ts.ScriptTarget.Latest,true,ts.ScriptKind.TS);
const functions=s=>new Map(parse(s).statements.filter(ts.isFunctionDeclaration).filter(n=>n.name).map(n=>[n.name.text,n.getText().replace(/^export /,'')]));
const oldFns=functions(before), newFns=functions(moduleText);
assert.deepEqual([...newFns.keys()],['parseBody','readRequestBuffer']);
for(const [name,text] of newFns) assert.equal(text,oldFns.get(name));
const publicExports=s=>parse(s).statements.filter(n=>ts.isExportDeclaration(n)||n.modifiers?.some(m=>m.kind===ts.SyntaxKind.ExportKeyword)).map(n=>n.getText());
assert.deepEqual(publicExports(after),publicExports(before));
fs.mkdirSync('verification',{recursive:true});
fs.writeFileSync('verification/index.before.ts',before);
fs.writeFileSync(sourcePath,after);
fs.writeFileSync('verification/extraction.json',JSON.stringify({base:'6110679a24c2a95179729b2f8c2c1a20f3227c50',index:hash(after),module:hash(moduleText),test:hash(testText),functionsUnchanged:[...newFns.keys()],exportsUnchanged:true,reconstructedByteExact:true,linesBefore:4416,linesAfter:4375},null,2)+'\n');
console.log('request_body_extraction_verified:'+hash(after));
